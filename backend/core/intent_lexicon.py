def prompt_lexicon_excerpt(limit: int = 5) -> str:
    """Return a compact lexicon excerpt for prompts."""

    sections = [
        ("城市", ["city_guangzhou", "city_shanghai"]),
        ("类别", ["category_coffee", "category_food", "category_library", "category_exhibition", "category_night"]),
        ("偏好", ["prefer_couple", "prefer_photo", "prefer_food", "prefer_culture", "prefer_local_feature", "prefer_night_view", "prefer_quiet", "prefer_rainy_day", "prefer_walking"]),
        ("避让", ["avoid_spicy", "avoid_far", "avoid_queue", "avoid_crowded"]),
    ]
    lines: list[str] = []
    for title, keys in sections:
        parts: list[str] = []
        for key in keys[:limit]:
            values = INTENT_LEXICON.get(key, [])
            alias_text = " / ".join(values[:3]) if values else "none"
            parts.append(f"{key}({alias_text})")
        lines.append(f"{title}: " + " | ".join(parts))
    lines.append(
        "扩展偏好: "
        + " | ".join(
            [
                "family(亲子 / 带娃 / 小朋友)",
                "friends(朋友 / 闺蜜 / 同学)",
                "solo(一个人 / 独自 / solo)",
                "value(性价比 / 划算 / 实惠)",
                "indoor(室内 / 室内优先 / 避雨)",
                "outdoor(室外 / 户外 / 露天)",
                "citywalk(citywalk / 散步 / 逛逛)",
                "efficient(高效 / 尽快 / 紧凑)",
                "compact(少绕路 / 少转场 / 不绕)",
            ][:limit]
        )
    )
    return "\n".join(lines)


